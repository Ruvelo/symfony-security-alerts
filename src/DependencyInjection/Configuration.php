<?php

declare(strict_types=1);

namespace Ruvelo\SecurityAlertsBundle\DependencyInjection;

use Ruvelo\SecurityAdvisories\Valtry\ValtryAdvisorySource;
use Symfony\Component\Config\Definition\Builder\ArrayNodeDefinition;
use Symfony\Component\Config\Definition\Configurator\DefinitionConfigurator;

/**
 * The `security_alerts:` config tree.
 */
final class Configuration
{
    public static function define(DefinitionConfigurator $definition): void
    {
        /** @var ArrayNodeDefinition $root */
        $root = $definition->rootNode();

        $root
            ->addDefaultsIfNotSet()
            ->children()
                ->booleanNode('enabled')
                    ->info('Turn the bundle off without removing it: nothing is registered')
                    ->defaultTrue()
                ->end()
                ->booleanNode('include_dev')
                    ->info('Check require-dev packages too. They are not deployed, so they are left out by default')
                    ->defaultFalse()
                ->end()
                ->enumNode('source')
                    ->info('Where advisories come from. valtry: Valtry\'s signed Advisory API, which is sent package names only (never versions), with Packagist, OSV and CISA used automatically whenever it can\'t answer. public: Packagist, OSV and CISA directly, nothing is sent to Valtry. RUVELO_ADVISORIES_SOURCE=public in the environment also opts out, and wins')
                    ->values(['valtry', 'public'])
                    ->defaultValue('valtry')
                ->end()
                ->scalarNode('valtry_url')
                    ->info('Valtry\'s Advisory API endpoint; only changed for a mirror or a test')
                    ->defaultValue(ValtryAdvisorySource::URL)
                    ->cannotBeEmpty()
                ->end()
                ->scalarNode('project_dir')
                    ->info('Where composer.lock (and package-lock.json, if any) live')
                    ->defaultValue('%kernel.project_dir%')
                    ->cannotBeEmpty()
                ->end()
                ->scalarNode('cache_pool')
                    ->info('Cache pool service for the advisory feeds; null fetches every time')
                    ->defaultValue('cache.app')
                ->end()
                ->arrayNode('cache_ttl')
                    ->info('How long feeds are cached, in seconds; 0 turns that cache off')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->integerNode('advisories')->min(0)->defaultValue(3600)->end()
                        ->integerNode('kev')->min(0)->defaultValue(21600)->end()
                        ->integerNode('osv_details')->min(0)->defaultValue(604800)->end()
                    ->end()
                ->end()
                ->arrayNode('http')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->scalarNode('client')
                            ->info('HttpClientInterface service to use; null uses a plain client')
                            ->defaultValue('http_client')
                        ->end()
                        ->floatNode('timeout')->info('Seconds per request')->min(1)->defaultValue(15)->end()
                        ->integerNode('tries')->info('Attempts per request; a refused connection or a 5xx is retried')->min(1)->defaultValue(2)->end()
                    ->end()
                ->end()
                ->arrayNode('state')
                    ->info('Where the known findings are kept, so only new ones are announced')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->enumNode('store')
                            ->info('filesystem: a dedicated pool that cache:clear leaves alone. pool: a cache pool of yours. doctrine: a table')
                            ->values(['filesystem', 'pool', 'doctrine'])
                            ->defaultValue('filesystem')
                        ->end()
                        ->scalarNode('directory')
                            ->info('For "filesystem"')
                            ->defaultValue('%kernel.project_dir%/var/security_alerts')
                            ->cannotBeEmpty()
                        ->end()
                        ->scalarNode('pool')->info('For "pool": a PSR-6 cache pool service id. Use a persistent one')->defaultNull()->end()
                        ->scalarNode('connection')->info('For "doctrine": a DBAL connection service id')->defaultValue('doctrine.dbal.default_connection')->end()
                        ->scalarNode('table')
                            ->info('For "doctrine": created on first use')
                            ->defaultValue('security_alerts_state')
                            ->validate()
                                ->ifTrue(static fn (mixed $v): bool => !\is_string($v) || 1 !== preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $v))
                                ->thenInvalid('The table name may only contain letters, digits and underscores.')
                            ->end()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('notify')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->arrayNode('recipients')
                            ->info('Email addresses to alert')
                            ->beforeNormalization()->ifString()->then(static fn (string $v): array => array_values(array_filter(array_map('trim', explode(',', $v)), static fn (string $s): bool => '' !== $s)))->end()
                            ->scalarPrototype()->cannotBeEmpty()->end()
                            ->defaultValue([])
                        ->end()
                        ->arrayNode('channels')
                            ->info('Notifier channels: "email", "chat", "chat/slack"... (email needs recipients; the others use your notifier config)')
                            ->beforeNormalization()->ifString()->then(static fn (string $v): array => [$v])->end()
                            ->scalarPrototype()->cannotBeEmpty()->end()
                            ->defaultValue(['email'])
                        ->end()
                        ->scalarNode('from')->info('Sender of the email; your mailer envelope sender is used when null')->defaultNull()->end()
                        ->scalarNode('app_name')->info('Named in subjects; the project directory name when null')->defaultNull()->end()
                        ->enumNode('min_severity')
                            ->info('Skip new findings below this. Exploited ones are always sent')
                            ->values([null, 'critical', 'high', 'medium', 'low'])
                            ->defaultNull()
                        ->end()
                    ->end()
                ->end()
                ->arrayNode('schedule')
                    ->info('The daily check, registered with symfony/scheduler when it is installed')
                    ->addDefaultsIfNotSet()
                    ->children()
                        ->booleanNode('enabled')->defaultTrue()->end()
                        ->scalarNode('time')
                            ->info('HH:MM')
                            ->defaultValue('07:00')
                            ->validate()
                                ->ifTrue(static fn (mixed $v): bool => !\is_string($v) || 1 !== preg_match('/^([01]?\d|2[0-3]):[0-5]\d$/', $v))
                                ->thenInvalid('The schedule time must look like 07:00.')
                            ->end()
                        ->end()
                        ->scalarNode('timezone')->info('The PHP default timezone when null')->defaultNull()->end()
                        ->scalarNode('name')->info('Name of the schedule, which gives the transport scheduler_<name>')->defaultValue('security_alerts')->end()
                    ->end()
                ->end()
            ->end();
    }
}
